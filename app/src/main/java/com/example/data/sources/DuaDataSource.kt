    fun searchDuas(query: String, categoryId: String): List<Dua> {
        val byCat = if (categoryId == "all") allDuas else allDuas.filter { it.categoryId == categoryId }
        if (query.isBlank()) return byCat

        val q = query.trim().lowercase()
        return byCat.filter { dua ->
            dua.titleBn.lowercase().contains(q) ||
            dua.situationBn.lowercase().contains(q) ||
            dua.banglaMeaning.lowercase().contains(q) ||
            dua.banglaPronunciation.lowercase().contains(q) ||
            dua.significanceBn.lowercase().contains(q) ||
            dua.referenceBn.lowercase().contains(q) ||
            dua.arabicText.contains(q)
        }
    }
